"""
六合彩AI智能预测系统 V5.0

data_quality.py

数据质量检测模块


功能:

1. 检查开奖数据完整性
2. 检查号码范围
3. 检查重复期号
4. 检查异常数据
5. 输出数据质量评分


"""


from collections import Counter





# =====================================================
# 基础检查
# =====================================================


def 检查基础数据(数据):


    if not 数据:

        return False



    if not isinstance(

        数据,

        list

    ):

        return False



    return True





# =====================================================
# 检查号码
# =====================================================


def 检查号码(号码):


    if not isinstance(

        号码,

        list

    ):

        return False



    # 正常六合彩:

    # 6个正码+1特码

    if len(号码) != 7:

        return False



    for num in 号码:


        try:

            num=int(num)

        except:


            return False



        if num < 1 or num > 49:

            return False



    return True





# =====================================================
# 检查重复号码
# =====================================================


def 检查重复号码(号码):


    return len(

        set(号码)

    ) == len(号码)





# =====================================================
# 检查期号
# =====================================================


def 检查期号(期号):


    if not 期号:

        return False



    return True





# =====================================================
# 单条开奖检测
# =====================================================


def 检查开奖(开奖):


    if not isinstance(

        开奖,

        dict

    ):

        return False



    if not 检查期号(

        开奖.get(

            "期号"

        )

    ):

        return False



    if not 检查号码(

        开奖.get(

            "号码",

            []

        )

    ):

        return False



    if not 检查重复号码(

        开奖.get(

            "号码"

        )

    ):

        return False



    return True





# =====================================================
# 批量检测
# =====================================================


def 检查历史数据(历史数据):


    if not 检查基础数据(

        历史数据

    ):

        return {


            "状态":

            "失败",


            "原因":

            "没有历史数据"

        }





    总数=len(

        历史数据

    )



    合格=0



    失败列表=[]



    期号记录=set()



    for index,item in enumerate(历史数据):


        if not 检查开奖(item):


            失败列表.append(

                index

            )


            continue





        期号=item["期号"]



        if 期号 in 期号记录:


            失败列表.append(

                index

            )


            continue



        期号记录.add(

            期号

        )



        合格 += 1





    评分=round(

        合格 / 总数 * 100,

        2

    )





    if 评分 >= 95:


        状态="优秀"



    elif 评分 >=80:


        状态="正常"



    else:


        状态="异常"





    return {


        "状态":

        状态,


        "质量评分":

        评分,


        "总数据":

        总数,


        "有效数据":

        合格,


        "异常数量":

        len(

            失败列表

        )


    }





# =====================================================
# 清理异常数据
# =====================================================


def 清理异常数据(历史数据):


    result=[]


    已存在=set()



    for item in 历史数据:


        if not 检查开奖(item):

            continue



        期号=item["期号"]



        if 期号 in 已存在:

            continue



        已存在.add(

            期号

        )


        result.append(

            item

        )



    return result





# =====================================================
# 数据统计
# =====================================================


def 数据统计(历史数据):


    if not 历史数据:


        return {}



    总期数=len(

        历史数据

    )



    号码=[]



    for item in 历史数据:


        号码.extend(

            item.get(

                "号码",

                []

            )

        )



    频率=Counter(

        号码

    )



    热门=频率.most_common(

        10

    )



    return {


        "历史期数":

        总期数,


        "号码数量":

        len(号码),


        "热门号码":

        热门

    }





# =====================================================
# V5统一入口
# =====================================================


def 数据质量分析(历史数据):


    检测=检查历史数据(

        历史数据

    )



    统计=数据统计(

        历史数据

    )



    return {


        "检测结果":

        检测,


        "统计":

        统计

    }





