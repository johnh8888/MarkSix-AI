from collections import Counter



# =====================================================
# 波色号码表
# =====================================================


红波 = {

    1,2,7,8,12,13,18,19,
    23,24,29,30,34,35,
    40,45,46

}



蓝波 = {

    3,4,9,10,14,15,
    20,25,26,31,36,
    37,41,42,47,48

}



绿波 = {

    5,6,11,16,17,21,
    22,27,28,32,33,
    38,39,43,44,49

}



波色列表 = [

    "红",

    "蓝",

    "绿"

]





# =====================================================
# 获取波色
# =====================================================


def 获取波色(num):


    num=int(num)


    if num in 红波:

        return "红"


    if num in 蓝波:

        return "蓝"


    if num in 绿波:

        return "绿"


    return "未知"





# =====================================================
# 单期开奖波色
# =====================================================


def 开奖波色(numbers):


    return [

        获取波色(x)

        for x in numbers

    ]





# =====================================================
# 波色统计
# =====================================================


def 波色统计(

        历史数据

):


    统计=Counter()



    for item in 历史数据:


        numbers=item.get(

            "号码",

            []

        )


        for num in numbers:


            统计[

                获取波色(num)

            ] +=1



    return dict(

        统计

    )





# =====================================================
# 波色概率
# =====================================================


def 波色概率(

        历史数据

):


    统计=波色统计(

        历史数据

    )


    总数=sum(

        统计.values()

    )



    if 总数==0:


        return {


            "红":0.33,

            "蓝":0.33,

            "绿":0.34

        }



    return {


        色:

        round(

            统计.get(

                色,

                0

            )

            /

            总数,

            4

        )


        for 色 in 波色列表

    }





# =====================================================
# 最近波色趋势
# =====================================================


def 最近波色趋势(

        历史数据,

        周期=20

):


    最近=历史数据[-周期:]



    统计=Counter()



    for item in 最近:


        numbers=item.get(

            "号码",

            []

        )



        # 特码最后一个号码

        if numbers:


            特码=numbers[-1]


            统计[

                获取波色(

                    特码

                )

            ]+=1



    总数=sum(

        统计.values()

    )



    if 总数==0:

        return {}



    return {


        色:

        round(

            统计.get(

                色,

                0

            )

            /

            总数,

            4

        )

        for 色 in 波色列表

    }





# =====================================================
# 连续波色检测
# =====================================================


def 检测连续波色(

        历史数据

):


    if len(历史数据)<2:

        return {


            "状态":

            "数据不足"

        }



    连续=0



    上一次=None



    for item in reversed(

        历史数据

    ):


        numbers=item.get(

            "号码",

            []

        )


        if not numbers:

            continue



        当前=获取波色(

            numbers[-1]

        )



        if 上一次 is None:


            上一次=当前

            连续=1


        elif 当前==上一次:


            连续+=1


        else:


            break



    return {


        "连续波色":

        上一次,


        "连续次数":

        连续

    }





# =====================================================
# 波色状态
# =====================================================


def 分析波色状态(

        历史数据

):


    概率=波色概率(

        历史数据

    )


    趋势=最近波色趋势(

        历史数据

    )


    连续=检测连续波色(

        历史数据

    )



    if 连续.get(

        "连续次数",

        0

    )>=3:


        状态="连续状态"



    else:


        状态="正常状态"





    return {


        "总体概率":

        概率,


        "近期趋势":

        趋势,


        "连续检测":

        连续,


        "市场状态":

        状态

    }





# =====================================================
# 波色评分
# =====================================================


def 波色评分(

        历史数据

):


    概率=波色概率(

        历史数据

    )


    评分={}



    for 色,value in 概率.items():


        评分[色]=round(

            value,

            4

        )



    return sorted(

        评分.items(),

        key=lambda x:x[1],

        reverse=True

    )





# =====================================================
# 推荐波色
# =====================================================


def 推荐波色(

        历史数据

):


    排序=波色评分(

        历史数据

    )


    单推=排序[0][0]


    双推=[

        x[0]

        for x in 排序[:2]

    ]



    排除=排序[-1][0]



    return {


        "波色单推":

        单推,


        "波色双推":

        双推,


        "波色排除":

        排除

    }





