# =====================================================
# 获取号码生肖
# =====================================================


def get_zodiac(number):


    try:


        number=int(number)



    except:


        return "未知"



    return 号码生肖表.get(

        number,

        "未知"

    )





# =====================================================
# 批量获取生肖
# =====================================================


def 获取生肖列表(numbers):


    return [

        get_zodiac(x)

        for x in numbers

    ]





# =====================================================
# 生肖统计
# =====================================================


def 生肖统计(历史数据):


    统计=Counter()



    for 开奖 in 历史数据:


        numbers=开奖.get(

            "号码",

            []

        )


        for num in numbers:


            生肖=get_zodiac(

                num

            )


            统计[生肖]+=1



    return dict(

        统计.most_common()

    )





# =====================================================
# 热门生肖
# =====================================================


def 热门生肖(

        历史数据,

        数量=5

):


    统计=生肖统计(

        历史数据

    )


    return list(

        统计.keys()

    )[:数量]





# =====================================================
# 生肖评分
# =====================================================


def 生肖评分(

        历史数据

):


    统计=生肖统计(

        历史数据

    )



    最大=max(

        统计.values()

    ) if 统计 else 1



    结果={}



    for 生肖,次数 in 统计.items():


        结果[生肖]=round(

            次数 /

            最大,

            4

        )



    return 结果





# =====================================================
# 生肖预测
# =====================================================


def 预测生肖(

        历史数据,

        数量=5

):


    评分=生肖评分(

        历史数据

    )


    排序=sorted(

        评分.items(),

        key=lambda x:x[1],

        reverse=True

    )


    return [

        x[0]

        for x in 排序[:数量]

    ]





