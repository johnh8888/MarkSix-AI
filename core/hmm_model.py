import math

from collections import Counter





# =====================================================
# 状态定义
# =====================================================


HMM_STATES=[

    "热态",

    "冷态",

    "平衡",

    "混沌"

]





# =====================================================
# 初始化
# =====================================================


def 初始化HMM():


    return {


        "状态概率":{


            state:0.25

            for state in HMM_STATES

        },


        "转移":{


            state:{

                s:0.25

                for s in HMM_STATES

            }

            for state in HMM_STATES

        }

    }





# =====================================================
# 熵计算
# =====================================================


def 计算熵(

        序列

):


    if not 序列:


        return 0



    counter=Counter(

        序列

    )



    total=len(

        序列

    )



    entropy=0



    for count in counter.values():


        p=count/total


        entropy-=p*math.log(

            p+1e-9

        )



    return round(

        entropy,

        4

    )





# =====================================================
# 特征判断状态
# =====================================================


def 判断状态(

        历史状态

):


    if len(历史状态)<5:


        return "平衡"





    最近=历史状态[-5:]



    counter=Counter(

        最近

    )



    最大次数=max(

        counter.values()

    )



    entropy=计算熵(

        最近

    )





    # 连续集中


    if 最大次数>=4:


        return "热态"





    # 熵高


    if entropy>1.5:


        return "混沌"





    # 长期少出现


    if 最大次数<=1:


        return "冷态"





    return "平衡"





# =====================================================
# 训练HMM
# =====================================================


def 训练HMM(

        历史状态

):


    hmm=初始化HMM()



    状态序列=[]



    for i in range(

        len(历史状态)

    ):


        状态序列.append(

            判断状态(

                历史状态[:i+1]

            )

        )





    # 统计状态转移


    for i in range(

        len(状态序列)-1

    ):


        当前=状态序列[i]


        下一个=状态序列[i+1]



        hmm["转移"][当前][下一个]+=1





    # 归一化


    for state,data in hmm["转移"].items():



        total=sum(

            data.values()

        )



        if total:


            for k in data:


                data[k]=round(

                    data[k]/total,

                    4

                )



    return hmm





# =====================================================
# 当前状态预测
# =====================================================


def 预测状态(

        hmm,

        当前状态

):


    转移=hmm["转移"].get(

        当前状态,

        {}

    )



    if not 转移:


        return {


            "状态":

            "平衡",


            "概率":

            0.25

        }





    状态=max(

        转移,

        key=转移.get

    )



    return {


        "状态":

        状态,


        "概率":

        转移[状态]

    }





# =====================================================
# HMM综合分析
# =====================================================


def hmm分析(

        历史数据

):


    状态序列=[]



    for item in 历史数据:


        nums=item.get(

            "号码",

            []

        )


        if nums:


            状态序列.append(

                nums[0]

            )





    hmm=训练HMM(

        状态序列

    )



    当前=判断状态(

        状态序列

    )



    下一=预测状态(

        hmm,

        当前

    )



    return {


        "当前状态":

        当前,


        "预测状态":

        下一,


        "模型":

        hmm

    }





