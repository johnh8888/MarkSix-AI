from enum import Enum

from collections import Counter





# =====================================================
# 市场状态定义
# =====================================================


class MarketState(Enum):


    平衡状态 = "平衡"


    热态 = "热态"


    冷态 = "冷态"


    连续状态 = "连续"


    反转状态 = "反转"


    混沌状态 = "混沌"





# =====================================================
# 状态中文
# =====================================================


def 状态名称(state):


    if isinstance(

        state,

        MarketState

    ):


        return state.value



    return str(state)





# =====================================================
# 波色连续检测
# =====================================================


def 检测连续波色(

        历史数据,

        周期=5

):


    if len(历史数据)<周期:


        return False



    最近=[]



    for item in 历史数据[-周期:]:


        波色=item.get(

            "波色",

            []

        )


        if 波色:


            最近.append(

                波色[-1]

            )



    if len(最近)<周期:


        return False



    return len(

        set(最近)

    )==1





# =====================================================
# 热号检测
# =====================================================


def 检测热态(

        历史数据,

        周期=20

):


    if len(历史数据)<周期:


        return False



    counter=Counter()



    for item in 历史数据[-周期:]:


        for num in item.get(

            "号码",

            []

        ):


            counter[num]+=1



    if not counter:


        return False



    最大次数=max(

        counter.values()

    )



    平均=sum(

        counter.values()

    ) / len(counter)



    return 最大次数 > 平均 * 2





# =====================================================
# 冷号检测
# =====================================================


def 检测冷态(

        历史数据,

        周期=30

):


    if len(历史数据)<周期:


        return False



    出现=set()



    for item in 历史数据[-周期:]:


        出现.update(

            item.get(

                "号码",

                []

            )

        )



    遗漏数量=49-len(

        出现

    )



    return 遗漏数量>=15





# =====================================================
# 大小趋势检测
# =====================================================


def 大小趋势(

        历史数据,

        周期=10

):


    结果=[]



    for item in 历史数据[-周期:]:


        numbers=item.get(

            "号码",

            []

        )


        if not numbers:

            continue



        特码=numbers[-1]



        if 特码>=25:


            结果.append(

                "大"

            )

        else:


            结果.append(

                "小"

            )



    return {

        "大":

        结果.count("大"),


        "小":

        结果.count("小")

    }





# =====================================================
# 单双趋势检测
# =====================================================


def 单双趋势(

        历史数据,

        周期=10

):


    结果=[]



    for item in 历史数据[-周期:]:


        numbers=item.get(

            "号码",

            []

        )


        if not numbers:

            continue



        特码=numbers[-1]



        if 特码 % 2:


            结果.append(

                "单"

            )

        else:


            结果.append(

                "双"

            )



    return {

        "单":

        结果.count("单"),


        "双":

        结果.count("双")

    }





# =====================================================
# 状态综合评分
# =====================================================


def 状态评分(

        历史数据

):


    score={

        "连续":

        0,

        "热":

        0,

        "冷":

        0,

        "反转":

        0

    }



    if 检测连续波色(

        历史数据

    ):


        score["连续"]+=2



    if 检测热态(

        历史数据

    ):


        score["热"]+=2



    if 检测冷态(

        历史数据

    ):


        score["冷"]+=2





    return score





# =====================================================
# 主状态判断
# =====================================================


def 分析市场状态(

        历史数据

):


    score=状态评分(

        历史数据

    )



    最大=max(

        score.values()

    )



    if 最大==0:


        return MarketState.平衡状态





    状态=max(

        score,

        key=score.get

    )



    if 状态=="连续":


        return MarketState.连续状态



    if 状态=="热":


        return MarketState.热态



    if 状态=="冷":


        return MarketState.冷态



    if 状态=="反转":


        return MarketState.反转状态



    return MarketState.平衡状态





# =====================================================
# 状态报告
# =====================================================


def 状态报告(

        历史数据

):


    state=分析市场状态(

        历史数据

    )



    return {


        "当前状态":

        状态名称(

            state

        ),



        "状态评分":

        状态评分(

            历史数据

        ),



        "大小趋势":

        大小趋势(

            历史数据

        ),



        "单双趋势":

        单双趋势(

            历史数据

        )

    }





