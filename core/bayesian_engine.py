"""
六合彩AI智能预测系统 V5.0

bayesian_engine.py

贝叶斯动态融合引擎


功能:

1. 模型可信度更新
2. 贝叶斯权重
3. 新旧数据衰减
4. 多模型融合
5. 输出号码概率


"""


import math


from collections import defaultdict





# =====================================================
# 贝叶斯参数
# =====================================================


默认先验={


    "frequency":

    1.0,


    "trend":

    1.0,


    "momentum":

    1.0,


    "omission":

    1.0,


    "wave":

    1.0,


    "zodiac":

    1.0,


    "size":

    1.0,


    "parity":

    1.0

}





# =====================================================
# 初始化模型参数
# =====================================================


def 初始化贝叶斯():

    return {


        模型:{

            "成功":

            1,


            "失败":

            1,


            "概率":

            0.5

        }


        for 模型 in 默认先验

    }





# =====================================================
# 更新模型结果
# =====================================================


def 更新模型(

        参数,

        模型,

        成功

):


    if 模型 not in 参数:


        参数[模型]={

            "成功":1,

            "失败":1,

            "概率":0.5

        }



    if 成功:


        参数[模型]["成功"]+=1


    else:


        参数[模型]["失败"]+=1





    成功次数=参数[模型]["成功"]


    失败次数=参数[模型]["失败"]



    参数[模型]["概率"]=round(

        成功次数 /

        (

            成功次数

            +

            失败次数

        ),

        4

    )


    return 参数





# =====================================================
# 模型可信度
# =====================================================


def 模型可信度(

        参数

):


    结果={}



    for 模型,data in 参数.items():


        结果[模型]=data.get(

            "概率",

            0.5

        )



    return 结果





# =====================================================
# 贝叶斯融合权重
# =====================================================


def 计算融合权重(

        参数

):


    可信度=模型可信度(

        参数

    )


    权重={}



    for 模型,概率 in 可信度.items():


        # 防止极端化

        权重[模型]=round(

            0.2

            +

            概率*0.8,

            4

        )



    总=sum(

        权重.values()

    )



    return {


        k:

        round(

            v/总,

            4

        )


        for k,v in 权重.items()

    }





# =====================================================
# 时间衰减
# =====================================================


def 时间衰减(

        天数,

        衰减率=0.03

):


    return round(

        math.exp(

            -衰减率*天数

        ),

        4

    )





# =====================================================
# 号码融合评分
# =====================================================


def 融合号码评分(

        模型结果,

        权重

):


    """
    
    模型结果格式:

    {
      frequency:
      {
        1:0.3,
        2:0.2
      },

      wave:
      {
        1:0.5
      }

    }


    """


    总评分=defaultdict(float)



    for 模型,号码数据 in 模型结果.items():


        w=权重.get(

            模型,

            0

        )



        for num,score in 号码数据.items():


            总评分[num]+=score*w





    return dict(

        sorted(

            总评分.items(),

            key=lambda x:x[1],

            reverse=True

        )

    )





# =====================================================
# 状态调整
# =====================================================


def 状态修正(

        权重,

        当前状态

):


    权重=权重.copy()



    if 当前状态=="混沌":


        for key in 权重:


            if key in [

                "frequency",

                "trend"

            ]:


                权重[key]*=0.7





    elif 当前状态=="连续":


        if "wave" in 权重:


            权重["wave"]*=1.2



    elif 当前状态=="冷态":


        if "omission" in 权重:


            权重["omission"]*=1.2





    总=sum(

        权重.values()

    )



    return {


        k:

        round(

            v/总,

            4

        )


        for k,v in 权重.items()

    }





# =====================================================
# V5最终入口
# =====================================================


def 贝叶斯预测融合(

        模型结果,

        参数,

        当前状态="平衡"

):


    权重=计算融合权重(

        参数

    )



    权重=状态修正(

        权重,

        当前状态

    )



    最终=融合号码评分(

        模型结果,

        权重

    )



    return {


        "号码评分":

        最终,


        "模型权重":

        权重,


        "状态":

        当前状态

    }





