# =====================================================
# 单期回测
# =====================================================


def 单期测试(

        历史训练,

        真实开奖

):


    结果={}



    预测=predict_next(

        历史训练

    )



    实际号码=真实开奖.get(

        "号码",

        []

    )



    推荐号码=预测.get(

        "特码10码",

        []

    )



    命中=[]



    for num in 推荐号码:


        if num in 实际号码:


            命中.append(num)





    结果["特码10码"]= {


        "预测":

        推荐号码,


        "实际":

        实际号码,


        "命中":

        命中,


        "数量":

        len(命中)

    }





    # 波色


    波色预测=predict_wave(

        历史训练

    )



    结果["波色"]=波色预测





    # 大小


    大小预测=predict_size(

        历史训练

    )



    结果["大小"]=大小预测





    # 单双


    单双预测=predict_parity(

        历史训练

    )



    结果["单双"]=单双预测





    # 生肖


    生肖预测=predict_zodiac(

        历史训练

    )



    结果["生肖"]=生肖预测





    return 结果





# =====================================================
# 命中统计
# =====================================================


def 统计命中(

        回测结果

):


    总期数=len(

        回测结果

    )


    if 总期数==0:


        return {}



    特码命中=0


    总号码=0



    for item in 回测结果:


        数量=item["特码10码"]["数量"]



        if 数量>0:


            特码命中+=1



        总号码+=数量





    return {


        "测试期数":

        总期数,


        "特码命中期数":

        特码命中,


        "期命中率":

        round(

            特码命中

            /

            总期数,

            4

        ),


        "平均命中号码":

        round(

            总号码

            /

            总期数,

            4

        )

    }





# =====================================================
# Walk Forward 回测
# =====================================================


def walk_forward(

        历史数据,

        开始位置=100

):


    结果=[]



    总长度=len(

        历史数据

    )



    for i in range(

        开始位置,

        总长度

    ):


        训练数据=历史数据[:i]



        测试数据=历史数据[i]



        单期结果=单期测试(

            训练数据,

            测试数据

        )



        单期结果["期号"]=测试数据.get(

            "期号",

            i

        )



        结果.append(

            单期结果

        )



    return 结果





# =====================================================
# 中文报告
# =====================================================


def 生成报告(

        回测结果

):


    统计=统计命中(

        回测结果

    )



    return {


        "系统":

        "六合彩AI V5.0",


        "模式":

        "Walk-Forward",


        "报告":

        {


            "测试期数":

            统计.get(

                "测试期数",

                0

            ),


            "特码命中率":

            str(

                round(

                    统计.get(

                        "期命中率",

                        0

                    )*100,

                    2

                )

            )

            +"%",


            "平均每期命中":

            统计.get(

                "平均命中号码",

                0

            )

        }

    }





# =====================================================
# 快速测试
# =====================================================


def 快速回测(

        历史数据,

        最近=50

):


    if len(历史数据)>最近+100:


        历史数据=历史数据[-(最近+100):]



    结果=walk_forward(

        历史数据

    )



    return 生成报告(

        结果

    )





