# -*- coding: utf-8 -*-

"""
六合彩 Walk-Forward 回测模块

功能：

1. 特码10码命中率
2. 特码5肖命中率
3. 平特2肖命中率
4. 大小命中率
5. 单双命中率
6. 波色单推命中率
7. ⭐ 波色双推2色命中率
8. ⭐ 波色双推相对单推提升

回测窗口：

10期
20期
30期
60期
100期

重要：

数据库没有 special 字段时：

numbers 第7个号码
作为特码。
"""


from .features import (
    get_special,
    get_wave,
)

from .predictor import (
    generate_prediction,
    NUMBER_TO_ZODIAC,
)


# =========================================================
# 获取真实开奖结果
# =========================================================

def get_actual_result(row):

    number = get_special(
        row
    )

    number = int(
        number
    )

    if not (
        1 <= number <= 49
    ):

        raise ValueError(
            f"无法获取有效特码：{number}"
        )

    # -----------------------------------------------------
    # 生肖
    # -----------------------------------------------------

    zodiac = NUMBER_TO_ZODIAC.get(
        number
    )

    # -----------------------------------------------------
    # 大小
    # -----------------------------------------------------

    if number >= 25:

        size = "大"

    else:

        size = "小"

    # -----------------------------------------------------
    # 单双
    # -----------------------------------------------------

    if number % 2:

        parity = "单"

    else:

        parity = "双"

    # -----------------------------------------------------
    # 波色
    # -----------------------------------------------------

    wave = get_wave(
        number
    )

    return {

        "number":
            number,

        "zodiac":
            zodiac,

        "size":
            size,

        "parity":
            parity,

        "wave":
            wave,
    }


# =========================================================
# 单期预测测试
# =========================================================

def test_one_prediction(
    prediction,
    actual
):

    # =====================================================
    # 特码10码
    # =====================================================

    top10 = [

        item["number"]

        for item in prediction.get(
            "top10_numbers",
            []
        )
    ]

    # =====================================================
    # 生肖5肖
    # =====================================================

    top5_zodiac = [

        item["zodiac"]

        for item in prediction.get(
            "top5_zodiac",
            []
        )
    ]

    # =====================================================
    # 平特2肖
    # =====================================================

    top2_pingte = [

        item["zodiac"]

        for item in prediction.get(
            "top2_pingte_zodiac",
            []
        )
    ]

    # =====================================================
    # 大小
    # =====================================================

    predicted_size = (

        prediction
        .get(
            "size",
            {}
        )
        .get(
            "prediction"
        )
    )

    # =====================================================
    # 单双
    # =====================================================

    predicted_parity = (

        prediction
        .get(
            "parity",
            {}
        )
        .get(
            "prediction"
        )
    )

    # =====================================================
    # ⭐ 波色
    # =====================================================

    wave_data = prediction.get(
        "wave",
        {}
    )

    # -----------------------------------------------------
    # 波色单推
    # -----------------------------------------------------

    predicted_wave = (
        wave_data.get(
            "prediction"
        )
    )

    # -----------------------------------------------------
    # ⭐ 波色双推
    # -----------------------------------------------------

    predicted_wave_top2 = [

        item["wave"]

        for item in wave_data.get(
            "top2",
            []
        )

        if isinstance(
            item,
            dict
        )
        and item.get("wave")
    ]

    # =====================================================
    # 判断
    # =====================================================

    result = {

        # -------------------------------------------------
        # 特码10码
        # -------------------------------------------------

        "number_hit":
            actual["number"]
            in top10,

        # -------------------------------------------------
        # 特码5肖
        # -------------------------------------------------

        "zodiac_hit":
            actual["zodiac"]
            in top5_zodiac,

        # -------------------------------------------------
        # 平特2肖
        # -------------------------------------------------

        "pingte_zodiac_hit":
            actual["zodiac"]
            in top2_pingte,

        # -------------------------------------------------
        # 大小
        # -------------------------------------------------

        "size_hit":
            predicted_size
            == actual["size"],

        # -------------------------------------------------
        # 单双
        # -------------------------------------------------

        "parity_hit":
            predicted_parity
            == actual["parity"],

        # -------------------------------------------------
        # 波色单推
        # -------------------------------------------------

        "wave_hit":
            predicted_wave
            == actual["wave"],

        # -------------------------------------------------
        # ⭐ 波色双推
        # -------------------------------------------------

        "wave_top2_hit":
            actual["wave"]
            in predicted_wave_top2,
    }

    return result


# =========================================================
# 单窗口回测
# =========================================================

def backtest(
    rows,
    max_tests=100
):

    rows = list(
        rows
    )

    # -----------------------------------------------------
    # 至少需要50期训练数据
    # -----------------------------------------------------

    if len(rows) < 60:

        return {

            "error":
                "历史数据不足60期",

            "tests":
                0,
        }

    # -----------------------------------------------------
    # 当前 rows：
    #
    # 最新 → 最旧
    #
    # 转换：
    #
    # 最旧 → 最新
    # -----------------------------------------------------

    chronological = list(
        reversed(rows)
    )

    total_available = len(
        chronological
    )

    # -----------------------------------------------------
    # 测试数量
    # -----------------------------------------------------

    test_count = min(

        max_tests,

        total_available - 50
    )

    if test_count <= 0:

        return {

            "error":
                "可用于回测的数据不足",

            "tests":
                0,
        }

    # -----------------------------------------------------
    # 测试开始位置
    # -----------------------------------------------------

    start_index = (

        total_available
        -
        test_count
    )

    # =====================================================
    # 统计
    # =====================================================

    stats = {

        "tests":
            0,

        "number_hits":
            0,

        "zodiac_hits":
            0,

        "pingte_zodiac_hits":
            0,

        "size_hits":
            0,

        "parity_hits":
            0,

        # 波色单推
        "wave_hits":
            0,

        # ⭐ 波色双推
        "wave_top2_hits":
            0,
    }

    # =====================================================
    # 详细记录
    # =====================================================

    details = []

    # =====================================================
    # Walk-Forward
    # =====================================================

    for i in range(
        start_index,
        total_available
    ):

        # -------------------------------------------------
        # 至少50期训练数据
        # -------------------------------------------------

        if i < 50:

            continue

        # -------------------------------------------------
        # 训练数据
        #
        # 不包含当前目标期
        # -------------------------------------------------

        train_rows = chronological[:i]

        # -------------------------------------------------
        # 目标开奖
        # -------------------------------------------------

        target_row = chronological[i]

        try:

            # =============================================
            # 预测
            # =============================================

            prediction = generate_prediction(
                train_rows
            )

            # =============================================
            # 实际结果
            # =============================================

            actual = get_actual_result(
                target_row
            )

            # =============================================
            # 比较
            # =============================================

            result = test_one_prediction(
                prediction,
                actual
            )

        except Exception as e:

            print()

            print(
                "回测错误：",
                e
            )

            print(
                "期号：",
                target_row.get(
                    "issue",
                    "未知"
                )
            )

            continue

        # =================================================
        # 总测试次数
        # =================================================

        stats["tests"] += 1

        # =================================================
        # 特码10码
        # =================================================

        if result["number_hit"]:

            stats["number_hits"] += 1

        # =================================================
        # 生肖5肖
        # =================================================

        if result["zodiac_hit"]:

            stats["zodiac_hits"] += 1

        # =================================================
        # 平特2肖
        # =================================================

        if result["pingte_zodiac_hit"]:

            stats[
                "pingte_zodiac_hits"
            ] += 1

        # =================================================
        # 大小
        # =================================================

        if result["size_hit"]:

            stats["size_hits"] += 1

        # =================================================
        # 单双
        # =================================================

        if result["parity_hit"]:

            stats["parity_hits"] += 1

        # =================================================
        # 波色单推
        # =================================================

        if result["wave_hit"]:

            stats["wave_hits"] += 1

        # =================================================
        # ⭐ 波色双推
        # =================================================

        if result["wave_top2_hit"]:

            stats[
                "wave_top2_hits"
            ] += 1

        # =================================================
        # 保存详细记录
        # =================================================

        details.append({

            "issue":
                target_row.get(
                    "issue"
                ),

            "actual_number":
                actual["number"],

            "actual_zodiac":
                actual["zodiac"],

            "actual_size":
                actual["size"],

            "actual_parity":
                actual["parity"],

            "actual_wave":
                actual["wave"],

            "number_hit":
                result["number_hit"],

            "zodiac_hit":
                result["zodiac_hit"],

            "pingte_zodiac_hit":
                result[
                    "pingte_zodiac_hit"
                ],

            "size_hit":
                result["size_hit"],

            "parity_hit":
                result["parity_hit"],

            "wave_hit":
                result["wave_hit"],

            "wave_top2_hit":
                result[
                    "wave_top2_hit"
                ],
        })

    # =====================================================
    # 最终统计
    # =====================================================

    total = stats["tests"]

    if total <= 0:

        return {

            "tests":
                0,

            "error":
                "没有成功完成任何回测",
        }

    # =====================================================
    # 各项命中率
    # =====================================================

    number_rate = (

        stats["number_hits"]
        /
        total
    )

    zodiac_rate = (

        stats["zodiac_hits"]
        /
        total
    )

    pingte_rate = (

        stats[
            "pingte_zodiac_hits"
        ]
        /
        total
    )

    size_rate = (

        stats["size_hits"]
        /
        total
    )

    parity_rate = (

        stats["parity_hits"]
        /
        total
    )

    # -----------------------------------------------------
    # 波色单推
    # -----------------------------------------------------

    wave_single_rate = (

        stats["wave_hits"]
        /
        total
    )

    # -----------------------------------------------------
    # ⭐ 波色双推
    # -----------------------------------------------------

    wave_top2_rate = (

        stats["wave_top2_hits"]
        /
        total
    )

    # -----------------------------------------------------
    # ⭐ 双推提升
    # -----------------------------------------------------

    wave_top2_gain = (

        wave_top2_rate
        -
        wave_single_rate
    )

    # =====================================================
    # 返回
    # =====================================================

    return {

        "tests":
            total,

        # -------------------------------------------------
        # 特码10码
        # -------------------------------------------------

        "number_top10_hit_rate":
            round(
                number_rate,
                6
            ),

        # -------------------------------------------------
        # 生肖5肖
        # -------------------------------------------------

        "zodiac_top5_hit_rate":
            round(
                zodiac_rate,
                6
            ),

        # -------------------------------------------------
        # 平特2肖
        # -------------------------------------------------

        "pingte_top2_hit_rate":
            round(
                pingte_rate,
                6
            ),

        # -------------------------------------------------
        # 大小
        # -------------------------------------------------

        "size_hit_rate":
            round(
                size_rate,
                6
            ),

        # -------------------------------------------------
        # 单双
        # -------------------------------------------------

        "parity_hit_rate":
            round(
                parity_rate,
                6
            ),

        # -------------------------------------------------
        # 波色单推
        # -------------------------------------------------

        "wave_hit_rate":
            round(
                wave_single_rate,
                6
            ),

        # -------------------------------------------------
        # ⭐ 波色双推
        # -------------------------------------------------

        "wave_top2_hit_rate":
            round(
                wave_top2_rate,
                6
            ),

        # -------------------------------------------------
        # ⭐ 双推提升
        # -------------------------------------------------

        "wave_top2_gain":
            round(
                wave_top2_gain,
                6
            ),

        # -------------------------------------------------
        # 详细记录
        # -------------------------------------------------

        "details":
            details[-100:],
    }


# =========================================================
# 多窗口回测
# =========================================================

def multi_window_backtest(rows):

    results = {}

    total = len(
        rows
    )

    windows = [

        10,

        20,

        30,

        60,

        100,
    ]

    # =====================================================
    # 每个窗口
    # =====================================================

    for window in windows:

        required = (
            window
            +
            50
        )

        # -------------------------------------------------
        # 数据不足
        # -------------------------------------------------

        if total < required:

            results[
                str(window)
            ] = {

                "window":
                    window,

                "tests":
                    0,

                "error":
                    (
                        f"数据不足，需要至少"
                        f"{required}期，"
                        f"当前只有{total}期"
                    ),
            }

            continue

        # -------------------------------------------------
        # 最近 window + 50期
        # -------------------------------------------------

        subset = rows[
            :required
        ]

        # -------------------------------------------------
        # 回测
        # -------------------------------------------------

        result = backtest(

            subset,

            max_tests=window
        )

        # -------------------------------------------------
        # 窗口
        # -------------------------------------------------

        result[
            "window"
        ] = window

        results[
            str(window)
        ] = result

    return results


