"""
六合彩回测模块

功能：

1. 特码10码命中率
2. 特码5肖命中率
3. 平特2肖命中率
4. 大小命中率
5. 单双命中率
6. 波色命中率

回测窗口：

10期
20期
30期
60期
100期

重要：

数据库没有 special 字段。

特码统一通过：

numbers 第7个号码

获取。

例如：

38,26,08,06,29,18,23
                    ↑
                   特码
"""


from .features import (
    get_special,
    get_wave,
)

from .predictor import (
    generate_prediction,
    NUMBER_TO_ZODIAC,
)


# =========================================================
# 获取真实开奖结果
# =========================================================

def get_actual_result(row):
    """
    从数据库记录中获取真实特码及属性。
    """

    # -----------------------------------------------------
    # 特码
    # -----------------------------------------------------

    number = get_special(row)

    # -----------------------------------------------------
    # 防止数据异常
    # -----------------------------------------------------

    if not (1 <= number <= 49):

        raise ValueError(
            f"无法获取有效特码：{number}"
        )

    # -----------------------------------------------------
    # 生肖
    # -----------------------------------------------------

    zodiac = NUMBER_TO_ZODIAC.get(
        number
    )

    # -----------------------------------------------------
    # 大小
    # -----------------------------------------------------

    if number >= 25:

        size = "大"

    else:

        size = "小"

    # -----------------------------------------------------
    # 单双
    # -----------------------------------------------------

    if number % 2:

        parity = "单"

    else:

        parity = "双"

    # -----------------------------------------------------
    # 波色
    # -----------------------------------------------------

    wave = get_wave(
        number
    )

    return {

        "number":
            number,

        "zodiac":
            zodiac,

        "size":
            size,

        "parity":
            parity,

        "wave":
            wave,
    }


# =========================================================
# 单期预测测试
# =========================================================

def test_one_prediction(
    prediction,
    actual
):
    """
    比较：

    预测结果
    VS
    实际开奖结果
    """

    # -----------------------------------------------------
    # 特码10码
    # -----------------------------------------------------

    top10 = [

        item["number"]

        for item in prediction.get(
            "top10_numbers",
            []
        )

    ]

    # -----------------------------------------------------
    # 特码5肖
    # -----------------------------------------------------

    top5_zodiac = [

        item["zodiac"]

        for item in prediction.get(
            "top5_zodiac",
            []
        )

    ]

    # -----------------------------------------------------
    # 平特2肖
    # -----------------------------------------------------

    top2_pingte = [

        item["zodiac"]

        for item in prediction.get(
            "top2_pingte_zodiac",
            []
        )

    ]

    # -----------------------------------------------------
    # 大小预测
    # -----------------------------------------------------

    predicted_size = (
        prediction
        .get("size", {})
        .get("prediction")
    )

    # -----------------------------------------------------
    # 单双预测
    # -----------------------------------------------------

    predicted_parity = (
        prediction
        .get("parity", {})
        .get("prediction")
    )

    # -----------------------------------------------------
    # 波色预测
    # -----------------------------------------------------

    predicted_wave = (
        prediction
        .get("wave", {})
        .get("prediction")
    )

    # =====================================================
    # 开始判断
    # =====================================================

    result = {

        # -------------------------------------------------
        # 特码10码
        # -------------------------------------------------

        "number_hit":
            actual["number"]
            in top10,

        # -------------------------------------------------
        # 特码5肖
        # -------------------------------------------------

        "zodiac_hit":
            actual["zodiac"]
            in top5_zodiac,

        # -------------------------------------------------
        # 平特2肖
        # -------------------------------------------------

        "pingte_zodiac_hit":
            actual["zodiac"]
            in top2_pingte,

        # -------------------------------------------------
        # 大小
        # -------------------------------------------------

        "size_hit":
            predicted_size
            == actual["size"],

        # -------------------------------------------------
        # 单双
        # -------------------------------------------------

        "parity_hit":
            predicted_parity
            == actual["parity"],

        # -------------------------------------------------
        # 波色
        # -------------------------------------------------

        "wave_hit":
            predicted_wave
            == actual["wave"],
    }

    return result


# =========================================================
# 单窗口回测
# =========================================================

def backtest(
    rows,
    max_tests=100
):
    """
    对指定历史数据进行 Walk-Forward 回测。

    rows：

        最新 -> 最旧

    回测时：

        最旧 -> 最新

    每一期：

        只使用该期之前的数据进行预测。

    防止未来数据泄漏。
    """

    # -----------------------------------------------------
    # 复制
    # -----------------------------------------------------

    rows = list(rows)

    # -----------------------------------------------------
    # 至少需要训练数据
    # -----------------------------------------------------

    if len(rows) < 60:

        return {

            "error":
                "历史数据不足60期",

            "tests":
                0,
        }

    # -----------------------------------------------------
    # 反转为：
    #
    # 最旧 -> 最新
    # -----------------------------------------------------

    chronological = list(
        reversed(rows)
    )

    total_available = len(
        chronological
    )

    # -----------------------------------------------------
    # 最大测试数量
    # -----------------------------------------------------

    test_count = min(
        max_tests,
        total_available - 50
    )

    if test_count <= 0:

        return {

            "error":
                "可用于回测的数据不足",

            "tests":
                0,
        }

    # -----------------------------------------------------
    # 测试开始位置
    # -----------------------------------------------------

    start_index = (
        total_available
        - test_count
    )

    # =====================================================
    # 统计
    # =====================================================

    stats = {

        "tests":
            0,

        "number_hits":
            0,

        "zodiac_hits":
            0,

        "pingte_zodiac_hits":
            0,

        "size_hits":
            0,

        "parity_hits":
            0,

        "wave_hits":
            0,
    }

    # =====================================================
    # 每一期详细记录
    # =====================================================

    details = []

    # =====================================================
    # Walk-Forward
    # =====================================================

    for i in range(
        start_index,
        total_available
    ):

        # -------------------------------------------------
        # 至少50期训练数据
        # -------------------------------------------------

        if i < 50:

            continue

        # -------------------------------------------------
        # 训练数据
        #
        # 注意：
        # 不包含当前目标期
        # -------------------------------------------------

        train_rows = chronological[:i]

        # -------------------------------------------------
        # 目标开奖
        # -------------------------------------------------

        target_row = chronological[i]

        try:

            # =============================================
            # 生成预测
            # =============================================

            prediction = generate_prediction(
                train_rows
            )

            # =============================================
            # 获取真实结果
            # =============================================

            actual = get_actual_result(
                target_row
            )

            # =============================================
            # 比较
            # =============================================

            result = test_one_prediction(
                prediction,
                actual
            )

        except Exception as e:

            print()
            print(
                "回测错误：",
                e
            )

            print(
                "期号：",
                target_row.get(
                    "issue",
                    "未知"
                )
            )

            continue

        # =================================================
        # 累计
        # =================================================

        stats["tests"] += 1

        # -------------------------------------------------
        # 特码10码
        # -------------------------------------------------

        if result["number_hit"]:

            stats["number_hits"] += 1

        # -------------------------------------------------
        # 特码5肖
        # -------------------------------------------------

        if result["zodiac_hit"]:

            stats["zodiac_hits"] += 1

        # -------------------------------------------------
        # 平特2肖
        # -------------------------------------------------

        if result["pingte_zodiac_hit"]:

            stats[
                "pingte_zodiac_hits"
            ] += 1

        # -------------------------------------------------
        # 大小
        # -------------------------------------------------

        if result["size_hit"]:

            stats["size_hits"] += 1

        # -------------------------------------------------
        # 单双
        # -------------------------------------------------

        if result["parity_hit"]:

            stats["parity_hits"] += 1

        # -------------------------------------------------
        # 波色
        # -------------------------------------------------

        if result["wave_hit"]:

            stats["wave_hits"] += 1

        # =================================================
        # 保存详细记录
        # =================================================

        details.append({

            "issue":
                target_row.get(
                    "issue"
                ),

            "actual_number":
                actual["number"],

            "actual_zodiac":
                actual["zodiac"],

            "actual_size":
                actual["size"],

            "actual_parity":
                actual["parity"],

            "actual_wave":
                actual["wave"],

            "number_hit":
                result["number_hit"],

            "zodiac_hit":
                result["zodiac_hit"],

            "pingte_zodiac_hit":
                result[
                    "pingte_zodiac_hit"
                ],

            "size_hit":
                result["size_hit"],

            "parity_hit":
                result["parity_hit"],

            "wave_hit":
                result["wave_hit"],
        })

    # =====================================================
    # 最终统计
    # =====================================================

    total = stats["tests"]

    if total <= 0:

        return {

            "tests":
                0,

            "error":
                "没有成功完成任何回测",
        }

    # =====================================================
    # 返回
    # =====================================================

    return {

        # -------------------------------------------------
        # 回测期数
        # -------------------------------------------------

        "tests":
            total,

        # -------------------------------------------------
        # 特码10码
        # -------------------------------------------------

        "number_top10_hit_rate":
            round(
                stats["number_hits"]
                / total,
                6
            ),

        # -------------------------------------------------
        # 特码5肖
        # -------------------------------------------------

        "zodiac_top5_hit_rate":
            round(
                stats["zodiac_hits"]
                / total,
                6
            ),

        # -------------------------------------------------
        # 平特2肖
        # -------------------------------------------------

        "pingte_top2_hit_rate":
            round(
                stats[
                    "pingte_zodiac_hits"
                ]
                / total,
                6
            ),

        # -------------------------------------------------
        # 大小
        # -------------------------------------------------

        "size_hit_rate":
            round(
                stats["size_hits"]
                / total,
                6
            ),

        # -------------------------------------------------
        # 单双
        # -------------------------------------------------

        "parity_hit_rate":
            round(
                stats["parity_hits"]
                / total,
                6
            ),

        # -------------------------------------------------
        # ⭐ 波色
        # -------------------------------------------------

        "wave_hit_rate":
            round(
                stats["wave_hits"]
                / total,
                6
            ),

        # -------------------------------------------------
        # 详细记录
        #
        # 最多保留最近100条
        # -------------------------------------------------

        "details":
            details[-100:],
    }


# =========================================================
# 多窗口回测
# =========================================================

def multi_window_backtest(rows):
    """
    同时进行：

    10期
    20期
    30期
    60期
    100期

    回测。

    注意：

    每个窗口都使用：

        window + 50

    条数据。

    其中：

        前50期 = 训练准备期

        后window期 = 实际回测期
    """

    results = {}

    total = len(rows)

    # =====================================================
    # 回测窗口
    # =====================================================

    windows = [

        10,

        20,

        30,

        60,

        100,

    ]

    # =====================================================
    # 逐窗口回测
    # =====================================================

    for window in windows:

        # -------------------------------------------------
        # 需要：
        #
        # 50期训练
        # +
        # window期测试
        # -------------------------------------------------

        required = (
            window + 50
        )

        if total < required:

            results[str(window)] = {

                "window":
                    window,

                "tests":
                    0,

                "error":
                    (
                        f"数据不足，需要至少"
                        f"{required}期，"
                        f"当前只有{total}期"
                    ),
            }

            continue

        # -------------------------------------------------
        # 使用最近 window + 50 期
        # -------------------------------------------------

        subset = rows[
            :required
        ]

        # -------------------------------------------------
        # 回测
        # -------------------------------------------------

        result = backtest(

            subset,

            max_tests=window

        )

        # -------------------------------------------------
        # 增加窗口信息
        # -------------------------------------------------

        result["window"] = window

        results[str(window)] = result

    return results


