# =====================================================
# 策略名称
# =====================================================


策略列表 = {


    "综合策略":

    "NORMAL",


    "追热策略":

    "HOT",


    "冷号策略":

    "COLD",


    "趋势策略":

    "TREND",


    "反转策略":

    "REVERSAL",


    "防守策略":

    "DEFENSE"

}





# =====================================================
# 默认策略权重
# =====================================================


默认策略权重={


    "frequency":0.20,


    "trend":0.15,


    "momentum":0.12,


    "omission":0.12,


    "wave":0.10,


    "zodiac":0.10,


    "size":0.08,


    "parity":0.05,


    "random":0.08

}





# =====================================================
# 状态选择策略
# =====================================================


def 选择策略(

        当前状态

):


    if isinstance(

        当前状态,

        MarketState

    ):


        当前状态=当前状态.value





    if 当前状态=="热态":


        return "追热策略"



    elif 当前状态=="冷态":


        return "冷号策略"



    elif 当前状态=="连续":


        return "趋势策略"



    elif 当前状态=="反转":


        return "反转策略"



    elif 当前状态=="混沌":


        return "防守策略"



    return "综合策略"





# =====================================================
# 策略权重调整
# =====================================================


def 调整权重(

        权重,

        策略

):


    新权重=权重.copy()



    if 策略=="追热策略":


        新权重["frequency"]*=1.3


        新权重["momentum"]*=1.2



        新权重["omission"]*=0.8





    elif 策略=="冷号策略":


        新权重["omission"]*=1.4


        新权重["trend"]*=1.2


        新权重["frequency"]*=0.8





    elif 策略=="趋势策略":


        新权重["trend"]*=1.3


        新权重["wave"]*=1.2





    elif 策略=="反转策略":


        新权重["omission"]*=1.3


        新权重["zodiac"]*=1.1


        新权重["frequency"]*=0.7





    elif 策略=="防守策略":


        新权重["random"]*=1.5


        新权重["frequency"]*=0.6


        新权重["trend"]*=0.6





    总=sum(

        新权重.values()

    )



    return {


        k:

        round(

            v/总,

            4

        )


        for k,v in 新权重.items()

    }





# =====================================================
# 风险等级
# =====================================================


def 风险评估(

        当前状态

):


    if 当前状态=="混沌":


        return {


            "等级":

            "高",


            "说明":

            "规律降低，降低追随强度"

        }





    if 当前状态=="连续":


        return {


            "等级":

            "中",


            "说明":

            "趋势明显，注意反转"

        }





    return {


        "等级":

        "低",


        "说明":

        "市场正常"

    }





# =====================================================
# 生成策略方案
# =====================================================


def 生成策略(

        当前状态,

        基础权重=None

):


    if 基础权重 is None:


        基础权重=默认策略权重





    策略=选择策略(

        当前状态

    )



    权重=调整权重(

        基础权重,

        策略

    )



    return {


        "当前状态":

        当前状态,


        "执行策略":

        策略,


        "模型权重":

        权重,


        "风险":

        风险评估(

            当前状态

        )

    }





# =====================================================
# 号码评分修正
# =====================================================


def 策略修正评分(

        号码评分,

        策略

):


    结果=号码评分.copy()



    if 策略=="防守策略":


        for num in 结果:


            结果[num]*=0.9





    elif 策略=="追热策略":


        for num in 结果:


            结果[num]*=1.05





    elif 策略=="冷号策略":


        for num in 结果:


            结果[num]*=1.03





    return dict(

        sorted(

            结果.items(),

            key=lambda x:x[1],

            reverse=True

        )

    )





